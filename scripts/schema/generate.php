<?php

/**
 * Schema generator: boots a Kirby installation with KQL and writes the schema
 * (src/schema.ts shape) as a TypeScript type.
 *
 *   php scripts/schema/generate.php <kirby-root> [<output.ts>]
 *
 * <kirby-root> is the folder with Kirby's index.php (and vendor/ or kirby/).
 * Without <output.ts> the schema is printed to stdout.
 *
 * What it reads:
 * The schema describes Kirby and KQL only: roots and methods registered by
 * plugins and KQL options in the site's config (`kql.interceptors`,
 * `kql.methods.*`) are left out.
 *
 * - classes: every built-in KQL interceptor, named by its CLASS_ALIAS. The
 *   Kirby class an interceptor wraps is its own name without `Kql\Interceptors\`.
 * - methods: the interceptor's allowed methods, its own public methods, Kirby
 *   methods and Kirby's custom methods marked `@kql-allowed`, and for `field`
 *   all of Kirby's field methods.
 * - return types: an override from overrides.php if there is one, else the PHP
 *   return type, else the docblock `@return` (also used when the PHP type is
 *   too vague, e.g. `array`, `mixed` or a class KQL cannot render), else what
 *   Kirby's `__call` gives (a file's asset method, a content field on models),
 *   else unknown. `static`, `$this` and `@template`s (`TValue`) resolve against
 *   the Kirby class the method is called on.
 * - model: classes whose unknown keys are content fields (KQL's Model
 *   interceptor where the Kirby class has content, and Content).
 * - default fields: the interceptor's `$toArray` keys.
 * - render: when the interceptor replaces `toArray`/`toResponse`, the return
 *   type of that method.
 * - item: for subclasses of Kirby\Cms\Collection (the ones KQL renders as a
 *   list), the collection's `TValue` template.
 * - roots: Kirby's query entries (`site`, `page(…)`, `kirby`, …), without those
 *   plugins register.
 * - blocks: the core blocks, from the block blueprints Kirby registers
 *   (`kirby/config/blocks`, not the site's), each field typed by what its
 *   field type stores in a block's content.
 */

use Kirby\Cms\App;
use Kirby\Kql\Interceptor;
use Kirby\Query\Query;

if (PHP_SAPI !== 'cli') {
	exit(1);
}

$root = $argv[1] ?? null;
$out  = $argv[2] ?? null;

if ($root === null || is_dir($root) === false) {
	fwrite(STDERR, "Usage: php scripts/schema/generate.php <kirby-root> [<output.ts>]\n");
	exit(1);
}

$root = realpath($root);

if (is_file($root . '/vendor/autoload.php') === true) {
	require $root . '/vendor/autoload.php';
}

if (class_exists(App::class) === false) {
	require $root . '/kirby/bootstrap.php';
}

$kirby = new App(['roots' => ['index' => $root]]);

if (class_exists(Interceptor::class) === false) {
	fwrite(STDERR, "The KQL plugin is not installed in $root\n");
	exit(1);
}

require_once __DIR__ . '/Generator.php';

$generator = new KqlSchemaGenerator($kirby, require __DIR__ . '/overrides.php');
$schema    = $generator->typescript(
	'Generated by `pnpm schema` from the Kirby installation at ' .
	($argv[1] === $root ? basename($root) : rtrim($argv[1], '/')) .
	' (Kirby ' . $kirby->version() . ', KQL ' . $generator->kqlVersion() . '). Do not edit.'
);

if ($out === null) {
	echo $schema;
} else {
	file_put_contents($out, $schema);
}
