/**
 * Records the fixtures: sends every test query through the real client to the
 * running test site (`pnpm site`) and writes, per group of test queries,
 *
 *   test/fixtures/<group>/<query>.json   the fixture
 *   test/fixtures/<group>.ts             the observed type of each fixture
 *
 * A test query exported as a list of queries has cases (e.g. the same query on
 * filled and on empty content). Its fixture is the list of their results, and
 * its observed type merges them like the items of one list.
 *
 * Every run wipes test/fixtures first.
 *
 * Every run also sets the modification time of every content file of the test
 * site to the same fixed date. A file's media URL (`file.url`, a default field
 * of files) contains its mtime, which a git checkout sets to the checkout
 * time. With a fixed mtime, the recorded URL is the same in every checkout.
 *
 * Usage: pnpm record
 */
import { mkdir, readdir, rm, utimes, writeFile } from 'node:fs/promises'
import { createClient, type Query } from '../src/index.ts'
import { testSite, testSiteByGroup } from '../test/test-site.ts'
import { observedType, observedTypeOfCases } from './observed-type.ts'

const queriesDir = new URL('../test/queries/', import.meta.url)
const fixturesDir = new URL('../test/fixtures/', import.meta.url)

/**
 * The groups of test queries checked on a client with block types (a `blocks`
 * key in its schema extension): their observed types tell blocks apart by
 * block type. Other groups see every block as one generic shape.
 */
const groupsWithBlockTypes = new Set(['blocks'])

const contentDir = new URL('../test/site/content/', import.meta.url)
const contentMtime = new Date('2026-01-01T00:00:00Z')

// Start from nothing, so fixtures of removed test queries or groups disappear.
await rm(fixturesDir, { recursive: true, force: true })

for (const entry of await readdir(contentDir, { recursive: true, withFileTypes: true })) {
	if (entry.isFile()) await utimes(`${entry.parentPath}/${entry.name}`, contentMtime, contentMtime)
}

for (const file of (await readdir(queriesDir)).filter((name) => name.endsWith('.ts')).sort()) {
	const group = file.replace(/\.ts$/, '')
	const queries: Record<string, Query | Query[]> = await import(new URL(file, queriesDir).href)
	const client = createClient(testSiteByGroup[group] ?? testSite)
	const groupDir = new URL(`${group}/`, fixturesDir)
	await mkdir(groupDir, { recursive: true })

	const options = { blockTypes: groupsWithBlockTypes.has(group) }

	const types: string[] = []
	for (const [name, query] of Object.entries(queries)) {
		const cases = Array.isArray(query)
		const fixture = cases
			? await Promise.all(query.map((single) => client.query(single)))
			: await client.query(query)
		const type = cases ? observedTypeOfCases(fixture as unknown[], options) : observedType(fixture, options)
		await writeFile(new URL(`${name}.json`, groupDir), `${JSON.stringify(fixture, null, '\t')}\n`)
		types.push(`\t${name}: ${type.replaceAll('\n', '\n\t')}`)
	}

	await writeFile(
		new URL(`${group}.ts`, fixturesDir),
		`// Generated by \`pnpm record\` from test/queries/${file}. Do not edit.\n\n` +
			`export interface Observed {\n${types.join('\n')}\n}\n`,
	)
	console.log(`${group}: ${types.length} fixture(s)`)
}
